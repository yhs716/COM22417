-- [CREATE-TABLE] CSV 원본·TRAIN/TEST 구분을 보존합니다. 특성은 오류 원문도 담는 VARCHAR2입니다.
-- 전처리한 숫자와 실제 학습제공여부 FIT_YN은 OML_BASIC_PREPARED에 별도로 저장합니다.
CREATE TABLE OML_BASIC_DATA
(
  CASE_ID NUMBER PRIMARY KEY
 , RETURN_PCT VARCHAR2(100)
 , RANGE_PCT VARCHAR2(100)
 , VOLUME_CHANGE_PCT VARCHAR2(100)
 , CLOSE_PRICE VARCHAR2(100)
 , STOCK VARCHAR2(100)
 , SIGNAL VARCHAR2(100)
 , WEEK_ENDING VARCHAR2(10)
 , SPLIT VARCHAR2(5) CHECK (SPLIT IN ('TRAIN', 'TEST'))
 , USE_YN CHAR(1) DEFAULT 'Y' NOT NULL CHECK (USE_YN IN ('Y', 'N'))
 , UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
)
;
