SELECT COUNT(*) TOTAL_ROWS
     , COUNT(CASE WHEN USE_YN = 'Y' THEN 1 END) USED_ROWS
     , COUNT(CASE WHEN USE_YN = 'N' THEN 1 END) DISABLED_ROWS
     , COUNT(CASE WHEN USE_YN = 'Y' AND SPLIT = 'TRAIN' THEN 1 END) TRAIN_ROWS
     , COUNT(CASE WHEN USE_YN = 'Y' AND SPLIT = 'TEST' THEN 1 END) TEST_ROWS
  FROM OML_BASIC_DATA
;
