-- 선택 모델명 뒤에 붙는 이름을 정확히 비교하여 같은 계정의 자동 생성 객체만 조회합니다.
-- NUM_ROWS는 Oracle 통계 값이며 현재 COUNT(*)가 아닙니다.
SELECT O.OBJECT_NAME
     , SUBSTR(O.OBJECT_NAME, 4, 2) AS INTERNAL_CODE
     , O.OBJECT_TYPE
     , O.STATUS
     , O.OBJECT_ID
     , O.CREATED
     , T.NUM_ROWS AS STATISTIC_ROWS
  FROM USER_OBJECTS O
  LEFT JOIN USER_TABLES T ON T.TABLE_NAME = O.OBJECT_NAME
 WHERE SUBSTR(O.OBJECT_NAME, 1, 3) = 'DM$'
   AND SUBSTR(O.OBJECT_NAME, 6) = :model_name
   AND O.OBJECT_TYPE IN ('TABLE', 'VIEW')
 ORDER BY O.OBJECT_TYPE, O.OBJECT_NAME
;
