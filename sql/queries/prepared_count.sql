-- [PREPARED-COUNT] FIT_YN이 실제 학습 제공 여부입니다. TEST는 평가에만 사용합니다.
SELECT PREP_MODE
     , COUNT(*) AS ROWS_COUNT
     , COUNT(CASE WHEN SOURCE_KIND = 'TRAIN' AND FIT_YN = 'Y' THEN 1 END) AS FIT_ROWS
     , COUNT(CASE WHEN SOURCE_KIND = 'TEST' AND USE_YN = 'Y' THEN 1 END) AS TEST_ROWS
  FROM {{table}}
 WHERE SOURCE_KIND IN ('TRAIN', 'TEST')
 GROUP BY PREP_MODE
;
