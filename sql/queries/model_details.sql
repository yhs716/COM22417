SELECT 'SETTING' SECTION
     , SETTING_NAME NAME
     , SETTING_VALUE VALUE
  FROM USER_MINING_MODEL_SETTINGS
 WHERE MODEL_NAME = :model_name
UNION ALL
SELECT 'ATTRIBUTE' SECTION
     , ATTRIBUTE_NAME NAME
     , DATA_TYPE VALUE
  FROM USER_MINING_MODEL_ATTRIBUTES
 WHERE MODEL_NAME = :model_name
;
