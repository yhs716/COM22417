SELECT C.COLUMN_NAME
     , C.DATA_TYPE
     , C.DATA_LENGTH
     , C.CHAR_LENGTH
     , C.CHAR_USED
     , C.DATA_PRECISION
     , C.DATA_SCALE
     , C.NULLABLE
     , C.DATA_DEFAULT
     , M.COMMENTS
  FROM USER_TAB_COLUMNS C
  LEFT JOIN USER_COL_COMMENTS M
    ON M.TABLE_NAME = C.TABLE_NAME
   AND M.COLUMN_NAME = C.COLUMN_NAME
 WHERE C.TABLE_NAME = :table_name
 ORDER BY C.COLUMN_ID
;
