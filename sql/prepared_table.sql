-- [CREATE-PREPARED-TABLE] 원본 DATA/PREDICT와 분리한 전처리 결과 저장소입니다.
-- PREPARE는 선택 방식의 TRAIN/TEST를, PREDICT는 선택 방식의 예측 입력만 교체합니다.
-- 학생 수정 위치: 특성·정답 컬럼과 아래 FIT_YN 제약을 02_procedure.sql/classifier.sql과 맞춥니다.
CREATE TABLE OML_BASIC_PREPARED
(
  PREP_MODE VARCHAR2(5) NOT NULL CHECK (PREP_MODE IN ('RAW', 'CLEAN'))
 , SOURCE_KIND VARCHAR2(7) NOT NULL CHECK (SOURCE_KIND IN ('TRAIN', 'TEST', 'PREDICT'))
 , CASE_ID NUMBER NOT NULL
 , RETURN_PCT NUMBER
 , RANGE_PCT NUMBER
 , VOLUME_CHANGE_PCT NUMBER
 , CLOSE_PRICE NUMBER
 , STOCK VARCHAR2(100)
 , SIGNAL VARCHAR2(100)
 , WEEK_ENDING VARCHAR2(10)
 , USE_YN CHAR(1) DEFAULT 'Y' NOT NULL CHECK (USE_YN IN ('Y', 'N'))
 , FIT_YN CHAR(1) DEFAULT 'N' NOT NULL CHECK (FIT_YN IN ('Y', 'N'))
 , EXCLUDE_REASON VARCHAR2(200)
 , PREPARED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
 , PRIMARY KEY (PREP_MODE, SOURCE_KIND, CASE_ID)
 , CHECK (FIT_YN = 'N' OR (SOURCE_KIND = 'TRAIN' AND USE_YN = 'Y'
          AND SIGNAL IS NOT NULL AND SIGNAL IN ('BUY', 'SELL')))
)
;
