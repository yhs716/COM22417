-- 기본과제 전용 초기화. 사용자 정의 객체와 DM$ 내부 객체는 직접 삭제하지 않습니다.
DECLARE
  v_count PLS_INTEGER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER') <> :owner
     OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> :owner THEN
    RAISE_APPLICATION_ERROR(-20030, '발급 계정과 CURRENT_SCHEMA를 확인하세요.');
  END IF;
  FOR model IN (SELECT MODEL_NAME FROM USER_MINING_MODELS
                 WHERE MODEL_NAME IN ('OML_BASIC_RAW_MODEL','OML_BASIC_CLEAN_MODEL')) LOOP
    DBMS_DATA_MINING.DROP_MODEL(model.MODEL_NAME);
  END LOOP;
  SELECT COUNT(*) INTO v_count FROM USER_OBJECTS
   WHERE OBJECT_NAME = 'OML_BASIC_RUN' AND OBJECT_TYPE = 'PROCEDURE';
  IF v_count > 0 THEN EXECUTE IMMEDIATE 'DROP PROCEDURE OML_BASIC_RUN'; END IF;
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'OML_BASIC_PREPARED';
  IF v_count > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OML_BASIC_PREPARED'; END IF;
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'OML_BASIC_PREDICT';
  IF v_count > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OML_BASIC_PREDICT'; END IF;
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'OML_BASIC_DATA';
  IF v_count > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OML_BASIC_DATA'; END IF;
END;
/
