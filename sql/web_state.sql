-- 검증 메타데이터만 준비합니다. 실습 테이블·모델·기존 기록은 삭제하지 않습니다.
DECLARE
  PRAGMA AUTONOMOUS_TRANSACTION;
  v_count NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') THEN
    RAISE_APPLICATION_ERROR(-20030, '발급 계정과 CURRENT_SCHEMA가 다릅니다.');
  END IF;
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'OML_WEB_STATE';
  IF v_count = 0 THEN
    BEGIN
      EXECUTE IMMEDIATE q'[
        CREATE TABLE OML_WEB_STATE
        (
          STATE_KEY VARCHAR2(64) PRIMARY KEY
         , REVISION NUMBER(18) NOT NULL
         , STATE_JSON CLOB NOT NULL CHECK (STATE_JSON IS JSON)
         , UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
        )]';
    EXCEPTION WHEN OTHERS THEN
      IF SQLCODE <> -955 THEN RAISE; END IF;
    END;
  END IF;
  COMMIT;
EXCEPTION WHEN OTHERS THEN
  ROLLBACK;
  RAISE;
END;
/
